// Authentication service – Email/Password, password reset (email link), Mobile OTP recovery.
import {
  createUserWithEmailAndPassword,
  signInWithEmailAndPassword,
  signOut,
  sendPasswordResetEmail,
  onAuthStateChanged,
  updateProfile,
  updatePassword,
  RecaptchaVerifier,
  signInWithPhoneNumber,
  linkWithPhoneNumber,
  deleteUser,
} from 'firebase/auth';
import { doc, getDoc, setDoc, writeBatch, serverTimestamp } from 'firebase/firestore';
import { fb } from '../shared/firebase.js';
import { CONFIG } from '../shared/config.js';
import { AppError } from '../shared/errors.js';

export const toE164 = (tenDigits) => `+91${String(tenDigits).replace(/\D/g, '').slice(-10)}`;

export function watchAuth(callback) {
  return onAuthStateChanged(fb().auth, callback);
}

export async function login(email, password) {
  const cred = await signInWithEmailAndPassword(fb().auth, email.trim(), password);
  return cred.user;
}

export async function logout() {
  await signOut(fb().auth);
}

let signupInProgress = false;

export async function signUp({ name, email, password, phone = '', ign = '', ffUid = '' }) {
  const { auth } = fb();
  signupInProgress = true;
  try {
    const cred = await createUserWithEmailAndPassword(auth, email.trim(), password);
    await updateProfile(cred.user, { displayName: name });
    await createUserDocs(cred.user, { name, phone, ign, ffUid });
    return cred.user;
  } finally {
    signupInProgress = false;
  }
}

/** Creates /users/{uid} profile + /wallets/{uid} (₹0 / ₹0) atomically. */
export async function createUserDocs(user, { name, phone = '', ign = '', ffUid = '' }) {
  const { db } = fb();
  const batch = writeBatch(db);
  batch.set(doc(db, 'users', user.uid), {
    uid: user.uid,
    name: String(name || user.displayName || 'Player').slice(0, 40),
    email: user.email,
    phone: String(phone || '').replace(/\D/g, '').slice(-10),
    ign: String(ign || '').slice(0, 24),
    ffUid: String(ffUid || '').replace(/\D/g, '').slice(0, 15),
    phoneVerified: false,
    banned: false,
    createdAt: serverTimestamp(),
  });
  batch.set(doc(db, 'wallets', user.uid), {
    deposit: 0,
    winning: 0,
    updatedAt: serverTimestamp(),
    lastRef: { type: 'init', id: user.uid },
  });
  await batch.commit();
}

/** Self-healing: creates profile/wallet if an earlier sign-up was interrupted. */
export async function ensureUserDocs(user) {
  if (signupInProgress) return;               // signUp() creates the docs itself
  const { db } = fb();
  const [p, w] = await Promise.all([getDoc(doc(db, 'users', user.uid)), getDoc(doc(db, 'wallets', user.uid))]);
  if (!p.exists() && user.email) {
    await setDoc(doc(db, 'users', user.uid), {
      uid: user.uid, name: (user.displayName || user.email.split('@')[0]).slice(0, 40).padEnd(2, '_'),
      email: user.email, phone: '', ign: '', ffUid: '', phoneVerified: false, banned: false,
      createdAt: serverTimestamp(),
    });
  }
  if (!w.exists()) {
    await setDoc(doc(db, 'wallets', user.uid), {
      deposit: 0, winning: 0, updatedAt: serverTimestamp(), lastRef: { type: 'init', id: user.uid },
    });
  }
}

export async function sendResetEmail(email) {
  await sendPasswordResetEmail(fb().auth, email.trim());
}

// ─────────────── Mobile OTP (Firebase Phone Auth) ───────────────
// Recovery flow: user links a verified mobile in Profile → later, "Forgot password → OTP"
// signs in with that number (same account) → sets a new password.

export function createRecaptcha(container) {
  return new RecaptchaVerifier(fb().auth, container, { size: 'invisible' });
}

export async function sendRecoveryOtp(tenDigits, verifier) {
  return signInWithPhoneNumber(fb().auth, toE164(tenDigits), verifier);
}

export async function sendLinkOtp(tenDigits, verifier) {
  const user = fb().auth.currentUser;
  if (!user) throw new AppError('AUTH', 'Please log in first.');
  return linkWithPhoneNumber(user, toE164(tenDigits), verifier);
}

/** Confirms a recovery OTP. Rejects (and cleans up) if the number is not linked to an email account. */
export async function confirmRecoveryOtp(confirmation, code) {
  const cred = await confirmation.confirm(code.trim());
  if (!cred.user.email) {
    try { await deleteUser(cred.user); } catch { await signOut(fb().auth); }
    throw new AppError('PHONE_NOT_LINKED', 'This mobile number is not linked to any account. Use the email reset option.');
  }
  return cred.user;
}

export async function setNewPassword(newPassword) {
  const user = fb().auth.currentUser;
  if (!user) throw new AppError('AUTH', 'Session expired. Please retry.');
  await updatePassword(user, newPassword);
}

/** Demo helper: read the OTP generated by the Auth Emulator (never available in production). */
export async function fetchEmulatorOtp(tenDigits) {
  if (!CONFIG.emulator) return null;
  const projectId = CONFIG.firebase.projectId;
  const res = await fetch(`/emulator/v1/projects/${projectId}/verificationCodes`);
  const json = await res.json();
  const list = (json.verificationCodes || []).filter((v) => v.phoneNumber === toE164(tenDigits));
  return list.length ? list[list.length - 1].code : null;
}
